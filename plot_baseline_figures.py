#!/usr/bin/env python3
"""Redraw Figs. 1, 3, 4, 5 as vector PDF from validated spectral/thermal data.

The baseline data must first be generated by qp_dkp_reproduce.py.
Run: python plot_baseline_figures.py --output-dir /path/to/tex/folder
"""
import argparse
import csv
import math
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt


def main(argv=None):
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--output-dir',type=Path,default=Path('reproduced/figures'))
    ap.add_argument('--data-dir',type=Path,default=Path('reproduced/data'))
    args=ap.parse_args(argv)
    args.output_dir.mkdir(parents=True,exist_ok=True)
    root=Path(__file__).parent
    args.data_dir.mkdir(parents=True,exist_ok=True)
    rows=list(csv.DictReader((args.data_dir/'baseline_observables.csv').open()))
    pairs=[(.1,.1),(.1,.2),(.2,.1),(.2,.3),(0.,0.)]
    colors=['#0072B2','#D55E00','#009E73','#CC79A7','#202020']
    styles=['-','--','-.',':',(0,(5,2))]
    labels=[r'$(\mu,\nu)=(0.1,0.1)$',r'$(\mu,\nu)=(0.1,0.2)$',
            r'$(\mu,\nu)=(0.2,0.1)$',r'$(\mu,\nu)=(0.2,0.3)$',
            r'Undeformed $(0,0)$']
    plt.rcParams.update({'font.size':11.5,'axes.labelsize':12.5,
        'legend.fontsize':10.5,'xtick.labelsize':10.5,'ytick.labelsize':10.5,
        'pdf.fonttype':42,'ps.fonttype':42,'axes.linewidth':.8,
        'lines.linewidth':1.9,'savefig.bbox':'tight'})
    def base(xlabel,ylabel):
        fig,ax=plt.subplots(figsize=(6.6,4.55),layout='constrained')
        ax.set_xlabel(xlabel);ax.set_ylabel(ylabel)
        ax.grid(True,color='.88',linewidth=.65)
        ax.set_axisbelow(True);ax.tick_params(direction='in',top=True,right=True)
        return fig,ax
    n=np.arange(31)
    fig,ax=base(r'Level index $n$',r'$\mathcal{E}_n=\epsilon_n^{(+)}/m$')
    spectral=[]
    for (mu,nu),c,ls,label in zip(pairs,colors,styles,labels):
        if nu==0:A=2*n
        else:
            num=lambda j:(np.exp(j*nu)-np.exp(-j*mu))/(math.exp(nu)-math.exp(-mu))
            A=num(n+1)+num(n)-1
            # Independent finite-sum identity, including exact n=0.
            f=lambda j:sum(math.exp((j-1-k)*nu-k*mu) for k in range(j))
            check=np.array([f(int(j+1))+f(int(j))-1 for j in n])
            assert np.allclose(A,check,rtol=3e-14,atol=3e-14)
        E=np.sqrt(1+A)
        spectral.extend(dict(mu=mu,nu=nu,n=int(j),E=float(e)) for j,e in zip(n,E))
        ax.plot(n,E,color=c,linestyle=ls,label=label,marker='o',markersize=2.5,markevery=3)
    ax.set_xlim(0,30);ax.set_ylim(bottom=0);ax.set_xticks(np.arange(0,31,5))
    ax.legend(loc='upper left',frameon=True,facecolor='white',framealpha=.96)
    fig.savefig(args.output_dir/'Fig1_spectrum_vector.pdf',metadata={'CreationDate':None,'ModDate':None});plt.close(fig)
    with (args.data_dir/'figure1_spectral_data.csv').open('w') as f:
        w=csv.DictWriter(f,fieldnames=['mu','nu','n','E']);w.writeheader();w.writerows(spectral)
    for key,ylabel,name,loc in [
        ('Z',r'$Z(\tau)$','Fig3_partition_vector.pdf','upper left'),
        ('F',r'$\mathcal{F}(\tau)=F_{\rm phys}/m$','Fig4_free_energy_vector.pdf','upper right'),
        ('U',r'$\mathcal{U}(\tau)=U_{\rm phys}/m$','Fig5_internal_energy_vector.pdf','upper left')]:
        fig,ax=base(r'$\tau=k_{\rm B}T/m$',ylabel)
        for pair,c,ls,label in zip(pairs,colors,styles,labels):
            subset=sorted([row for row in rows if (float(row['mu']),float(row['nu']))==pair],key=lambda row:float(row['tau']))
            assert len(subset)==199
            x=np.array([float(row['tau']) for row in subset])
            y=np.array([float(row[key]) for row in subset])
            ax.plot(x,y,color=c,linestyle=ls,label=label)
        ax.set_xlim(.1,10)
        ax.legend(loc=loc,frameon=True,facecolor='white',framealpha=.96)
        fig.savefig(args.output_dir/name,metadata={'CreationDate':None,'ModDate':None});plt.close(fig)
    print('Four vector PDF figures created; 155 spectrum rows checked; 995 validated thermal rows reused.')


if __name__=='__main__':main()
